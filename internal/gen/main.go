// Command gen generates Go code from the OPC UA schema files
// (Opc.Ua.Types.bsd, NodeIds.csv, StatusCode.csv).
//
// Usage: go run ./internal/gen -schema internal/gen/schema -out .
package main

import (
	"bytes"
	"encoding/csv"
	"encoding/xml"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

type bsdDoc struct {
	Items []bsdItem `xml:",any"`
}

type bsdItem struct {
	XMLName      xml.Name
	Name         string     `xml:"Name,attr"`
	BaseType     string     `xml:"BaseType,attr"`
	LengthInBits int        `xml:"LengthInBits,attr"`
	IsOptionSet  bool       `xml:"IsOptionSet,attr"`
	Fields       []bsdField `xml:"Field"`
	Values       []bsdValue `xml:"EnumeratedValue"`
}

type bsdField struct {
	Name        string `xml:"Name,attr"`
	TypeName    string `xml:"TypeName,attr"`
	LengthField string `xml:"LengthField,attr"`
	SwitchField string `xml:"SwitchField,attr"`
}

type bsdValue struct {
	Name  string `xml:"Name,attr"`
	Value int64  `xml:"Value,attr"`
}

var builtinStructs = map[string]bool{
	"XmlElement": true, "TwoByteNodeId": true, "FourByteNodeId": true, "NumericNodeId": true,
	"StringNodeId": true, "GuidNodeId": true, "ByteStringNodeId": true, "NodeId": true,
	"ExpandedNodeId": true, "DiagnosticInfo": true, "QualifiedName": true, "LocalizedText": true,
	"DataValue": true, "ExtensionObject": true, "Variant": true,
}

type prim struct{ goType, write, read string }

var prims = map[string]prim{
	"opc:Boolean":        {"bool", "WriteBool", "ReadBool"},
	"opc:SByte":          {"int8", "WriteInt8", "ReadInt8"},
	"opc:Byte":           {"byte", "WriteUint8", "ReadUint8"},
	"opc:Char":           {"byte", "WriteUint8", "ReadUint8"},
	"opc:Int16":          {"int16", "WriteInt16", "ReadInt16"},
	"opc:UInt16":         {"uint16", "WriteUint16", "ReadUint16"},
	"opc:Int32":          {"int32", "WriteInt32", "ReadInt32"},
	"opc:UInt32":         {"uint32", "WriteUint32", "ReadUint32"},
	"opc:Int64":          {"int64", "WriteInt64", "ReadInt64"},
	"opc:UInt64":         {"uint64", "WriteUint64", "ReadUint64"},
	"opc:Float":          {"float32", "WriteFloat32", "ReadFloat32"},
	"opc:Double":         {"float64", "WriteFloat64", "ReadFloat64"},
	"opc:String":         {"string", "WriteString", "ReadString"},
	"opc:CharArray":      {"string", "WriteString", "ReadString"},
	"opc:ByteString":     {"[]byte", "WriteByteString", "ReadByteString"},
	"opc:DateTime":       {"time.Time", "WriteDateTime", "ReadDateTime"},
	"opc:Guid":           {"Guid", "WriteGuid", "ReadGuid"},
	"ua:XmlElement":      {"XmlElement", "WriteXmlElement", "ReadXmlElement"},
	"ua:NodeId":          {"NodeId", "WriteNodeId", "ReadNodeId"},
	"ua:ExpandedNodeId":  {"ExpandedNodeId", "WriteExpandedNodeId", "ReadExpandedNodeId"},
	"ua:StatusCode":      {"StatusCode", "WriteStatusCode", "ReadStatusCode"},
	"ua:QualifiedName":   {"QualifiedName", "WriteQualifiedName", "ReadQualifiedName"},
	"ua:LocalizedText":   {"LocalizedText", "WriteLocalizedText", "ReadLocalizedText"},
	"ua:ExtensionObject": {"ExtensionObject", "WriteExtensionObject", "ReadExtensionObject"},
	"ua:DataValue":       {"DataValue", "WriteDataValue", "ReadDataValue"},
	"ua:Variant":         {"Variant", "WriteVariant", "ReadVariant"},
	"ua:DiagnosticInfo":  {"*DiagnosticInfo", "WriteDiagnosticInfo", "ReadDiagnosticInfo"},
}

func main() {
	schema := flag.String("schema", "internal/gen/schema", "schema directory")
	out := flag.String("out", ".", "module root")
	flag.Parse()

	ids := readNodeIds(filepath.Join(*schema, "NodeIds.csv"))
	genIds(ids, filepath.Join(*out, "ua", "id", "ids_gen.go"))
	genStatus(filepath.Join(*schema, "StatusCode.csv"), filepath.Join(*out, "ua", "status_gen.go"))
	genTypes(filepath.Join(*schema, "Opc.Ua.Types.bsd"), ids, filepath.Join(*out, "ua", "types_gen.go"))
}

type nodeIdEntry struct {
	name  string
	id    uint32
	class string
}

func readNodeIds(path string) []nodeIdEntry {
	f, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	r := csv.NewReader(f)
	r.FieldsPerRecord = -1
	recs, err := r.ReadAll()
	if err != nil {
		log.Fatal(err)
	}
	var out []nodeIdEntry
	for _, rec := range recs {
		if len(rec) < 3 {
			continue
		}
		v, err := strconv.ParseUint(rec[1], 10, 32)
		if err != nil {
			continue
		}
		out = append(out, nodeIdEntry{rec[0], uint32(v), rec[2]})
	}
	return out
}

func writeGo(path string, src []byte) {
	formatted, err := format.Source(src)
	if err != nil {
		os.WriteFile(path+".broken", src, 0o644)
		log.Fatalf("format %s: %v", path, err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}

func genIds(ids []nodeIdEntry, path string) {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen from NodeIds.csv. DO NOT EDIT.\n\n")
	b.WriteString("// Package id contains the numeric identifiers of the nodes in namespace 0.\n")
	b.WriteString("package id\n\nconst (\n")
	for _, e := range ids {
		fmt.Fprintf(&b, "\t%s = %d // %s\n", e.name, e.id, e.class)
	}
	b.WriteString(")\n")
	writeGo(path, b.Bytes())
}

func genStatus(csvPath, path string) {
	f, err := os.Open(csvPath)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	r := csv.NewReader(f)
	r.FieldsPerRecord = -1
	recs, err := r.ReadAll()
	if err != nil {
		log.Fatal(err)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen from StatusCode.csv. DO NOT EDIT.\n\npackage ua\n\nconst (\n")
	var names []string
	for _, rec := range recs {
		if len(rec) < 2 {
			continue
		}
		desc := ""
		if len(rec) > 2 {
			desc = strings.ReplaceAll(rec[2], "\n", " ")
		}
		fmt.Fprintf(&b, "\t// Status%s: %s\n\tStatus%s StatusCode = %s\n", rec[0], desc, rec[0], rec[1])
		names = append(names, rec[0])
	}
	b.WriteString(")\n\nvar statusNames = map[StatusCode]string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\tStatus%s: %q,\n", n, n)
	}
	b.WriteString("}\n")
	writeGo(path, b.Bytes())
}

func goIdent(s string) string {
	var sb strings.Builder
	upper := true
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) && r != '_' {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		sb.WriteRune(r)
	}
	out := sb.String()
	if out == "" || unicode.IsDigit(rune(out[0])) {
		out = "V" + out
	}
	return out
}

func genTypes(bsdPath string, ids []nodeIdEntry, path string) {
	raw, err := os.ReadFile(bsdPath)
	if err != nil {
		log.Fatal(err)
	}
	var doc bsdDoc
	if err := xml.Unmarshal(raw, &doc); err != nil {
		log.Fatal(err)
	}
	idByName := map[string]uint32{}
	for _, e := range ids {
		idByName[e.name] = e.id
	}

	enums := map[string]bsdItem{}
	structs := map[string]bsdItem{}
	opaques := map[string]bsdItem{}
	var order []string
	for _, it := range doc.Items {
		switch it.XMLName.Local {
		case "EnumeratedType":
			if it.Name != "NodeIdType" {
				enums[it.Name] = it
				order = append(order, it.Name)
			}
		case "StructuredType":
			if !builtinStructs[it.Name] {
				structs[it.Name] = it
				order = append(order, it.Name)
			}
		case "OpaqueType":
			opaques[it.Name] = it
		}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen from Opc.Ua.Types.bsd. DO NOT EDIT.\n\n")
	b.WriteString("package ua\n\nimport \"time\"\n\nvar _ time.Time\n\n")

	enumWidth := func(e bsdItem) prim {
		switch e.LengthInBits {
		case 8:
			return prim{"byte", "WriteUint8", "ReadUint8"}
		case 16:
			return prim{"uint16", "WriteUint16", "ReadUint16"}
		case 64:
			return prim{"uint64", "WriteUint64", "ReadUint64"}
		}
		if e.IsOptionSet {
			return prim{"uint32", "WriteUint32", "ReadUint32"}
		}
		return prim{"int32", "WriteInt32", "ReadInt32"}
	}

	// Enumerations.
	for _, name := range order {
		e, ok := enums[name]
		if !ok {
			continue
		}
		w := enumWidth(e)
		gn := goIdent(name)
		fmt.Fprintf(&b, "// %s is defined in Opc.Ua.Types.bsd.\ntype %s %s\n\nconst (\n", gn, gn, w.goType)
		for _, v := range e.Values {
			fmt.Fprintf(&b, "\t%s%s %s = %d\n", gn, goIdent(v.Name), gn, v.Value)
		}
		b.WriteString(")\n\n")
		fmt.Fprintf(&b, "func (v %s) String() string {\n\tswitch v {\n", gn)
		seen := map[int64]bool{}
		for _, v := range e.Values {
			if seen[v.Value] {
				continue
			}
			seen[v.Value] = true
			fmt.Fprintf(&b, "\tcase %d:\n\t\treturn %q\n", v.Value, v.Name)
		}
		fmt.Fprintf(&b, "\t}\n\treturn \"%s(\" + itoa(int64(v)) + \")\"\n}\n\n", gn)
	}

	type fieldInfo struct {
		name    string
		goType  string
		array   bool
		write   string // expression format with %s = value
		read    string // statement format with %s = target
		elemTyp string
	}

	resolve := func(tn string) (goType, write, read string) {
		if p, ok := prims[tn]; ok {
			return p.goType, "e." + p.write + "(%s)", "%s = d." + p.read + "()"
		}
		local := strings.TrimPrefix(tn, "tns:")
		if e, ok := enums[local]; ok {
			w := enumWidth(e)
			gn := goIdent(local)
			return gn, "e." + w.write + "(" + w.goType + "(%s))", "%s = " + gn + "(d." + w.read + "())"
		}
		if _, ok := structs[local]; ok {
			gn := goIdent(local)
			return gn, "e.WriteStruct(&%s)", "d.ReadStruct(&%s)"
		}
		if _, ok := opaques[local]; ok {
			return "[]byte", "e.WriteByteString(%s)", "%s = d.ReadByteString()"
		}
		log.Fatalf("unknown type %s", tn)
		return
	}

	var registered []string
	for _, name := range order {
		s, ok := structs[name]
		if !ok {
			continue
		}
		gn := goIdent(name)
		lengthFields := map[string]bool{}
		for _, f := range s.Fields {
			if f.LengthField != "" {
				lengthFields[f.LengthField] = true
			}
			if f.SwitchField != "" || f.TypeName == "opc:Bit" {
				log.Fatalf("%s: optional fields are not supported", name)
			}
		}
		var fields []fieldInfo
		for _, f := range s.Fields {
			if lengthFields[f.Name] {
				continue
			}
			gt, w, r := resolve(f.TypeName)
			fi := fieldInfo{name: goIdent(f.Name), goType: gt, write: w, read: r, array: f.LengthField != ""}
			fi.elemTyp = gt
			fields = append(fields, fi)
		}

		dtID, hasDT := idByName[name]
		encID, hasEnc := idByName[name+"_Encoding_DefaultBinary"]

		fmt.Fprintf(&b, "// %s is defined in Opc.Ua.Types.bsd.\ntype %s struct {\n", gn, gn)
		for _, f := range fields {
			if f.array {
				fmt.Fprintf(&b, "\t%s []%s\n", f.name, f.goType)
			} else {
				fmt.Fprintf(&b, "\t%s %s\n", f.name, f.goType)
			}
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "// DataTypeID returns the NodeId of the %s DataType.\n", name)
		fmt.Fprintf(&b, "func (*%s) DataTypeID() NodeId { return NewNumericNodeId(0, %d) }\n\n", gn, dtID)
		fmt.Fprintf(&b, "// BinaryEncodingID returns the NodeId of the %s DefaultBinary encoding.\n", name)
		fmt.Fprintf(&b, "func (*%s) BinaryEncodingID() NodeId { return NewNumericNodeId(0, %d) }\n\n", gn, encID)

		// Service requests and responses start with their header.
		if len(fields) > 0 && !fields[0].array && fields[0].name == fields[0].goType &&
			(fields[0].goType == "RequestHeader" || fields[0].goType == "ResponseHeader") {
			fmt.Fprintf(&b, "// Header returns the %s.\nfunc (v *%s) Header() *%s { return &v.%s }\n\n",
				fields[0].goType, gn, fields[0].goType, fields[0].name)
		}

		fmt.Fprintf(&b, "// Encode writes the structure in UA Binary encoding.\nfunc (v *%s) Encode(e *Encoder) {\n", gn)
		for _, f := range fields {
			target := "v." + f.name
			if f.array {
				fmt.Fprintf(&b, "\te.WriteArrayLength(len(%s), %s == nil)\n", target, target)
				fmt.Fprintf(&b, "\tfor i := range %s {\n\t\t%s\n\t}\n", target, fmt.Sprintf(f.write, target+"[i]"))
			} else {
				fmt.Fprintf(&b, "\t%s\n", fmt.Sprintf(f.write, target))
			}
		}
		b.WriteString("}\n\n")

		fmt.Fprintf(&b, "// Decode reads the structure in UA Binary encoding.\nfunc (v *%s) Decode(d *Decoder) {\n", gn)
		for _, f := range fields {
			target := "v." + f.name
			if f.array {
				fmt.Fprintf(&b, "\tif n := d.ReadArrayLength(); n >= 0 {\n\t\t%s = make([]%s, n)\n", target, f.goType)
				fmt.Fprintf(&b, "\t\tfor i := range %s {\n\t\t\t%s\n\t\t}\n\t} else {\n\t\t%s = nil\n\t}\n",
					target, fmt.Sprintf(f.read, target+"[i]"), target)
			} else {
				fmt.Fprintf(&b, "\t%s\n", fmt.Sprintf(f.read, target))
			}
		}
		b.WriteString("}\n\n")
		if hasDT && hasEnc {
			registered = append(registered, gn)
		}
	}
	sort.Strings(registered)
	b.WriteString("func init() {\n")
	for _, gn := range registered {
		fmt.Fprintf(&b, "\tRegisterStructure(func() Structure { return new(%s) })\n", gn)
	}
	b.WriteString("}\n\n")
	b.WriteString("var structNames = map[string]func() Structure{\n")
	var all []string
	for _, name := range order {
		if _, ok := structs[name]; ok {
			all = append(all, name)
		}
	}
	sort.Strings(all)
	for _, name := range all {
		fmt.Fprintf(&b, "\t%q: func() Structure { return new(%s) },\n", name, goIdent(name))
	}
	b.WriteString("}\n\n// NewStructureByName creates an empty structure by its schema name.\n")
	b.WriteString("func NewStructureByName(name string) Structure {\n\tif f, ok := structNames[name]; ok {\n\t\treturn f()\n\t}\n\treturn nil\n}\n")
	writeGo(path, b.Bytes())
}
